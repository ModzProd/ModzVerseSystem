-- FIX 1: workers.style — promotion style -> worker in-ring style
-- 
-- PWS uses workers.style to look up STYLE_PROFILES in
-- StatConverter.js for stat distribution. None of the
-- promotion-style values ('Pure Wrestling', 'Kings Road',
-- 'Sports Entertainment') are valid keys — every wrestler
-- was silently using DEFAULT_PROFILE instead.
-- ============================================================

UPDATE workers SET style='Entertainer' WHERE style='Sports Entertainment';  -- 60 wrestlers (Sports Entertainment -> Entertainer)
UPDATE workers SET style='Technical' WHERE style='Pure Wrestling';  -- 44 wrestlers (Pure Wrestling -> Technical)
UPDATE workers SET style='Strong Style' WHERE style='Kings Road';  -- 80 wrestlers (Kings Road -> Strong Style)

-- ============================================================
-- FIX 2: contracts.push='None' -> NULL
-- 
-- 135 contracts have the literal string 'None' instead of NULL.
-- PWS expects either a valid push tier (Main Event, Midcard,
-- etc.) or NULL. The string 'None' shows up as a phantom
-- option in the push filter dropdown.
-- ============================================================

UPDATE contracts SET push=NULL WHERE push='None';  -- 0 contracts

-- ============================================================
-- FIX 3: contracts.role — invalid values -> NULL
-- 
-- PWS expects role to be 'Face', 'Heel', 'Tweener', 'Announcer',
-- or empty/NULL. We had:
--   195 contracts with role='None' (should be NULL)
--   12 contracts with role='Personality' (should be NULL)
--   88 contracts with role='Wrestler' (should be NULL)
-- ============================================================

UPDATE contracts SET role=NULL WHERE role='Personality';  -- 12 contracts
UPDATE contracts SET role=NULL WHERE role='Wrestler';  -- 88 contracts

